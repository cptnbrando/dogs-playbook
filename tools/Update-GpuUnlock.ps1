<#
.SYNOPSIS
    Refreshes the vendored gpu-unlock snapshot and regenerates the device table
    the playbook's optional GPU check reads.

.DESCRIPTION
    third_party/gpu-unlock is a pinned, unmodified snapshot of
    https://github.com/Zagitta/gpu-unlock (GPL-2.0-only). It is reference
    material only: it is a Linux kernel module and is NOT packed into the
    .apbx (build.ps1 only archives ./src).

    src/Executables/GPU-UNLOCK/supported-devices.json is generated from the
    snapshot's kernel/gpu_unlock/recipes.c. It is plain PCI device-ID data.

.PARAMETER Ref
    Upstream branch, tag or commit to pin. Default: main.

.PARAMETER SkipDownload
    Only regenerate supported-devices.json from the snapshot already on disk.

.EXAMPLE
    ./tools/Update-GpuUnlock.ps1
    ./tools/Update-GpuUnlock.ps1 -Ref 7eb51bccae0a0b7e599e084d971170e9a1e82d0c
    ./tools/Update-GpuUnlock.ps1 -SkipDownload
#>
[CmdletBinding()]
param(
    [string]$Ref = 'main',
    [switch]$SkipDownload
)

$ErrorActionPreference = 'Stop'
$repoRoot   = Split-Path -Parent $PSScriptRoot
$vendorDir  = Join-Path $repoRoot 'third_party/gpu-unlock'
$upstreamMd = Join-Path $vendorDir 'UPSTREAM.md'
$outJson    = Join-Path $repoRoot 'src/Executables/GPU-UNLOCK/supported-devices.json'
$upstream   = 'Zagitta/gpu-unlock'

if (-not $SkipDownload) {
    $headers = @{ 'User-Agent' = 'dogs-playbook-updater'; 'Accept' = 'application/vnd.github+json' }
    $commit  = Invoke-RestMethod -Headers $headers -Uri "https://api.github.com/repos/$upstream/commits/$Ref"
    $sha     = $commit.sha
    Write-Host "Pinning $upstream at $sha" -ForegroundColor Cyan

    $tmp = Join-Path ([IO.Path]::GetTempPath()) ("gpu-unlock-" + [guid]::NewGuid())
    New-Item -ItemType Directory -Path $tmp | Out-Null
    try {
        $tarball = Join-Path $tmp 'src.tar.gz'
        Invoke-WebRequest -Headers $headers -Uri "https://codeload.github.com/$upstream/tar.gz/$sha" -OutFile $tarball
        $extract = Join-Path $tmp 'x'
        New-Item -ItemType Directory -Path $extract | Out-Null
        tar -xzf $tarball -C $extract --strip-components=1
        if ($LASTEXITCODE -ne 0) { throw "tar failed with exit code $LASTEXITCODE" }

        if (Test-Path $vendorDir) { Remove-Item -Recurse -Force $vendorDir }
        New-Item -ItemType Directory -Path $vendorDir | Out-Null
        Copy-Item -Path (Join-Path $extract '*') -Destination $vendorDir -Recurse -Force
        Get-ChildItem -Path $extract -Force -Filter '.*' | Copy-Item -Destination $vendorDir -Recurse -Force
    } finally {
        Remove-Item -Recurse -Force $tmp -ErrorAction SilentlyContinue
    }

    @"
# Vendored upstream: gpu-unlock

- Source: https://github.com/$upstream
- Commit: ``$sha``
- Fetched: $(Get-Date -Format 'yyyy-MM-dd')
- License: GPL-2.0-only (see ``licenses/`` and ``firmware/NOTICE.md`` in this folder)

This folder is an unmodified snapshot, kept for reference and auditing. It is
a **Linux** kernel module: nothing here runs on Windows, and nothing here is
packed into the playbook ``.apbx``. The playbook only ships
``src/Executables/GPU-UNLOCK/supported-devices.json``, generated from
``kernel/gpu_unlock/recipes.c`` by ``tools/Update-GpuUnlock.ps1``.

Do not edit files in this folder; re-run the updater instead.
"@ | Set-Content -Path $upstreamMd -Encoding UTF8
}

if (-not (Test-Path $upstreamMd)) { throw "No snapshot at $vendorDir. Run without -SkipDownload first." }
$sha = ([regex]::Match((Get-Content $upstreamMd -Raw), 'Commit: `([0-9a-f]{40})`')).Groups[1].Value
if (-not $sha) { throw "Could not read the pinned commit from $upstreamMd" }

$recipes = Get-Content (Join-Path $vendorDir 'kernel/gpu_unlock/recipes.c') -Raw

# Generation metadata, from the upstream README's "Supported GPUs" table.
$generations = [ordered]@{
    TU = [ordered]@{ generation = 'Turing';       series = 'RTX 20'; linuxStatus = 'experimental' }
    GA = [ordered]@{ generation = 'Ampere';       series = 'RTX 30'; linuxStatus = 'stable' }
    AD = [ordered]@{ generation = 'Ada Lovelace'; series = 'RTX 40'; linuxStatus = 'experimental' }
}

$devices = New-Object System.Collections.Generic.List[object]
$seen = @{}
foreach ($line in ($recipes -split "`n")) {
    if ($line -match '^\s*#') { continue }   # skip the #define TU102(id) ... macros
    foreach ($m in [regex]::Matches($line, '\b((TU|GA|AD)1\d\d)\((0x[0-9a-fA-F]{4})\)')) {
        $id = $m.Groups[3].Value.Substring(2).ToLower()
        if ($seen.ContainsKey($id)) { continue }
        $seen[$id] = $true
        $devices.Add([ordered]@{ id = $id; chip = $m.Groups[1].Value; family = $m.Groups[2].Value })
    }
}
if ($devices.Count -lt 50) { throw "Parsed only $($devices.Count) device IDs from recipes.c; the upstream format probably changed." }

$doc = [ordered]@{
    '$comment'  = 'Generated by tools/Update-GpuUnlock.ps1. Do not edit by hand.'
    source      = "https://github.com/$upstream"
    commit      = $sha
    vendorId    = '10de'
    families    = $generations
    windowsPort = [ordered]@{
        url   = 'https://github.com/impacifist/Windows-GPU-UNLOCK'
        scope = 'Experimental UEFI pre-boot port. Success reports are for specific desktop RTX 30 (Ampere) card + motherboard combinations only. Requires Secure Boot off, BitLocker off and a separate EFI System Partition.'
    }
    devices     = $devices | Sort-Object { $_.id }
}

New-Item -ItemType Directory -Force -Path (Split-Path $outJson) | Out-Null
$doc | ConvertTo-Json -Depth 5 | Set-Content -Path $outJson -Encoding UTF8
Write-Host "Wrote $($devices.Count) device IDs to $outJson" -ForegroundColor Green
